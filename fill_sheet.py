def main() -> None:
    client = get_client()
    sheet = client.open_by_key(config.GOOGLE_SHEET_ID).worksheet(config.GOOGLE_SHEET_NAME)
    rows = sheet.get_all_values()

    rows_to_delete = [
        i + 1
        for i, row in enumerate(rows)
        if i > 0 and row and (row[0].strip(), row[1].strip()) in OLD_RECORDS
    ]
    for row_idx in sorted(rows_to_delete, reverse=True):
        sheet.delete_rows(row_idx)

    existing = sheet.get_all_values()
    existing_map = {
        (r[0].strip(), r[1].strip()): (i + 1)
        for i, r in enumerate(existing)
        if i > 0 and r and len(r) > 1
    }
    headers = [h.strip() for h in existing[0]]

    added = 0
    updated = 0
    for row in ROWS:
        key = (row[0], row[1])
        if key in existing_map:
            row_num = existing_map[key]
            sheet.update(values=[row], range_name=f"A{row_num}")
            updated += 1
        else:
            sheet.append_rows([row], value_input_option="USER_ENTERED")
            added += 1

    print(f"Deleted {len(rows_to_delete)} old records, added {added}, updated {updated}")


if __name__ == "__main__":
    main()
